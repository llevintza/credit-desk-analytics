-- ADR-0027: cost of the admin Usage reads over app.audit (#70).
-- Builds a copy of app.audit (same columns, PK and IX_audit_at) in a throwaway database, fills it with 90 days of
-- synthetic rows (the ADR-0022 default retention window), then times the candidate statements for
-- GET /api/admin/usage with EXPLAIN ANALYZE. Local throwaway Postgres only (trust auth); never Neon or production.
--
-- Volume: :rows_per_day rows a day (default 10,000, the ADR-0022 busy demo). Window: :days days (default 30).
\set ON_ERROR_STOP on
\if :{?rows_per_day}
\else
  \set rows_per_day 10000
\endif
\if :{?days}
\else
  \set days 30
\endif
\if :{?fill}
\else
  \set fill on
\endif

\if :fill
DROP TABLE IF EXISTS audit;
CREATE TABLE audit (
    id bigint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT "PK_audit" PRIMARY KEY,
    at timestamp with time zone NOT NULL,
    kind character varying(16) NOT NULL,
    user_name character varying(256),
    endpoint character varying(256) NOT NULL,
    status integer NOT NULL,
    rows integer,
    ms integer NOT NULL,
    cache character varying(8)
);
CREATE INDEX "IX_audit_at" ON audit (at);

-- 90 days ending at a fixed "now"; synthetic users and endpoints like the real ones, a few logins and no-cache rows.
INSERT INTO audit (at, kind, user_name, endpoint, status, rows, ms, cache)
SELECT timestamptz '2026-10-16 12:00+00' - (g * (interval '90 days' / (:rows_per_day * 90))),
       CASE WHEN g % 50 = 0 THEN 'login_success' ELSE 'request' END,
       'viewer-' || (g % 7) || '@example.com',
       (ARRAY['POST /api/positions/query', 'GET /api/insights/{source}', 'GET /api/meta/columns', 'GET /api/deals'])[1 + g % 4],
       200, 500, 5 + ((g::bigint * 7919) % 900)::int,
       (ARRAY['HIT', 'MISS', NULL])[1 + g % 3]
FROM generate_series(1, :rows_per_day * 90) AS g;
VACUUM ANALYZE audit;
\endif

\echo '--- per user per day (one GROUP BY over the window)'
EXPLAIN (ANALYZE, BUFFERS, COSTS OFF, SUMMARY ON)
SELECT (at AT TIME ZONE 'UTC')::date AS day, user_name,
       count(*) AS requests,
       count(*) FILTER (WHERE cache = 'HIT') AS hits,
       count(*) FILTER (WHERE cache = 'MISS') AS misses,
       count(*) FILTER (WHERE status >= 500) AS errors,
       round(avg(ms))::int AS avg_ms
FROM audit
WHERE at >= timestamptz '2026-10-17 00:00+00' - make_interval(days => :days) AND kind = 'request'
GROUP BY 1, 2;

\echo '--- slowest 20 per day, (a) ROW_NUMBER over the window'
EXPLAIN (ANALYZE, BUFFERS, COSTS OFF, SUMMARY ON)
SELECT day, at, user_name, endpoint, status, rows, ms, cache
FROM (SELECT (at AT TIME ZONE 'UTC')::date AS day, at, user_name, endpoint, status, rows, ms, cache,
             row_number() OVER (PARTITION BY (at AT TIME ZONE 'UTC')::date ORDER BY ms DESC, id) AS rn
      FROM audit
      WHERE at >= timestamptz '2026-10-17 00:00+00' - make_interval(days => :days) AND kind = 'request') ranked
WHERE rn <= 20;

\echo '--- slowest 20 per day, (b) LATERAL top-N per day'
EXPLAIN (ANALYZE, BUFFERS, COSTS OFF, SUMMARY ON)
SELECT (d AT TIME ZONE 'UTC')::date AS day, s.*
FROM generate_series(timestamptz '2026-10-17 00:00+00' - make_interval(days => :days),
                     timestamptz '2026-10-16 00:00+00', interval '1 day') AS d
CROSS JOIN LATERAL (
    SELECT at, user_name, endpoint, status, rows, ms, cache
    FROM audit
    WHERE at >= d AND at < d + interval '1 day' AND kind = 'request'
    ORDER BY ms DESC, id
    LIMIT 20) s;

\echo '--- (c) the whole report in one statement: GROUP BY + LATERAL as two CTEs'
EXPLAIN (ANALYZE, BUFFERS, COSTS OFF, SUMMARY ON)
WITH days AS (
    SELECT (at AT TIME ZONE 'UTC')::date AS day, user_name, count(*) AS requests
    FROM audit
    WHERE at >= timestamptz '2026-10-17 00:00+00' - make_interval(days => :days) AND kind = 'request'
    GROUP BY 1, 2),
slow AS (
    SELECT (d AT TIME ZONE 'UTC')::date AS day, s.ms
    FROM generate_series(timestamptz '2026-10-17 00:00+00' - make_interval(days => :days),
                         timestamptz '2026-10-16 00:00+00', interval '1 day') AS d
    CROSS JOIN LATERAL (
        SELECT ms FROM audit WHERE at >= d AND at < d + interval '1 day' AND kind = 'request'
        ORDER BY ms DESC, id LIMIT 20) s)
SELECT (SELECT count(*) FROM days), (SELECT count(*) FROM slow);
